// Regenerates src/constants/imageDimensions.ts from public/images.
// Run after adding or replacing images: pnpm run gen:images
import sharp from 'sharp';
import { readdirSync, writeFileSync } from 'fs';
import path from 'path';

const dir = 'public/images';
const entries = {};

for (const file of readdirSync(dir).sort()) {
  if (!/\.(webp|png|jpe?g|avif)$/i.test(file)) continue;
  const { width, height } = await sharp(path.join(dir, file)).metadata();
  entries[`/images/${file}`] = { width, height };
}

const out = `// Generated by scripts/generate-image-dimensions.mjs — do not edit by hand.
export const IMAGE_DIMENSIONS: Record<string, { width: number; height: number }> = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync('src/constants/imageDimensions.ts', out);
console.log(`wrote ${Object.keys(entries).length} entries to src/constants/imageDimensions.ts`);
